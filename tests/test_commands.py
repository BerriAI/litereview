"""PR comments select saved reviewers while tolerating surrounding prose."""

import pytest
from sqlalchemy import select
from test_reviews import create, mock_github, payload, setup, webhook

from app import reviews
from app.db import Job, Run, Session


@pytest.mark.parametrize("body", [
    "@litereview code-review review this pls",
    "hello @litereview code-review",
    "@LiteReview: CODE-REVIEW, review this please!",
    "@litereview **code-review** review this pls",
    "@litereview `code-review` review this pls",
    "@litereview code-review; echo unsafe",
    "@litereview\ncode-review\nreview this pls",
    "@litereview code-review\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
    "@litereview code-review\n\nreviewer is mentioned in another paragraph.",
    "@litereview code-review [reviewer](https://example.com)",
    "@litereview code-review\n\n> @litereview reviewer",
    "@litereview code-review\n\n```text\n@litereview reviewer\n```",
])
def test_webhook_selects_exact_saved_reviewer_with_prose(owner, monkeypatch, body):
    _, _, template, _, _ = setup(owner)
    agent = create(owner, "agents", **{**template, "name": "code-review"})
    mock_github(monkeypatch)
    response = webhook(owner, payload(body=body))
    assert response.status_code == 200
    with Session() as db:
        assert db.get(Run, response.json()["run_id"]).status == "queued"
        jobs = db.scalars(select(Job)).all()
        assert len(jobs) == 1
        assert jobs[0].status == "queued"
        assert jobs[0].config["agent_id"] == agent["id"]
        # Prose selects reviewers; it does not replace their saved instructions.
        assert jobs[0].config["instructions"] == template["instructions"]


@pytest.mark.parametrize("body", [
    "```text\n@litereview reviewer\n```",
    "    @litereview reviewer",
    "Try `@litereview reviewer` for a review.",
    "> @litereview reviewer",
    "[Run @litereview reviewer](https://example.com)",
    "![@litereview reviewer](https://example.com/example.png)",
    "<!-- @litereview reviewer -->",
    "<pre>@litereview reviewer</pre>",
    "Try <code>@litereview reviewer</code> for a review.",
    'Try <a href="https://example.com">@litereview reviewer</a> for a review.',
    "@litereviewer reviewer",
    "@litereview-bot reviewer",
    "@litereview/command reviewer",
    "@litereview.example reviewer",
    "person@litereview reviewer",
    "https://example.com/@litereview reviewer",
])
def test_examples_and_unrelated_mentions_do_not_start_reviews(owner, monkeypatch, body):
    setup(owner)
    mock_github(monkeypatch)
    assert not reviews.is_command(body)
    assert webhook(owner, payload(body=body)).json()["ignored"]
    with Session() as db:
        assert not db.scalars(select(Run)).all()
        assert not db.scalars(select(Job)).all()


@pytest.mark.parametrize("body", [
    "@litereview unknown review this pls",
    "@litereview reviewer-extra",
    "@litereview my-reviewer",
    "@litereview [reviewer](https://example.com)",
    "@litereview unknown\n\nreviewer",
])
def test_no_exact_saved_name_rejects_without_falling_back_to_default(owner, monkeypatch, body):
    setup(owner)
    mock_github(monkeypatch)
    response = webhook(owner, payload(body=body))
    with Session() as db:
        run = db.get(Run, response.json()["run_id"])
        assert run.status == "rejected"
        assert "unavailable" in run.snapshot["rejection"]
        assert not db.scalars(select(Job)).all()


def test_multiple_mentions_and_default_deduplicate_in_selection_order(owner, monkeypatch):
    setup(owner)
    mock_github(monkeypatch)
    response = webhook(owner, payload(body=(
        "Please @litereview general and reviewer review this pls. "
        "@litereview reviewer\n\n@litereview"
    )))
    with Session() as db:
        run = db.get(Run, response.json()["run_id"])
        assert [group["name"] for group in run.snapshot["groups"]] == ["general", "reviewer"]
        jobs = db.scalars(select(Job).where(Job.run_id == run.id)).all()
        assert [job.config["group"] for job in reviews.ordered_jobs(run, jobs)] == [
            "general", "general", "reviewer",
        ]
